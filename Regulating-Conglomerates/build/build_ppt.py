# ------------------------------------------------------------- text measuring

def est_lines(text, width_in, size_pt):
    """Conservative line estimate: treat every char as full-width CJK."""
    px = width_in * 96.0
    char_px = size_pt * 96.0 / 72.0
    per_line = max(1, int(px / char_px))
    total = 0
    for seg in str(text).split("\n"):
        total += max(1, -(-len(seg) // per_line))
    return total


def est_height(text, width_in, size_pt, spacing=1.15):
    return est_lines(text, width_in, size_pt) * size_pt * spacing / 72.0 + 0.06


def fit_image(path, bw, bh):
    """Return (w,h) fitting image into box preserving aspect."""
    iw, ih = Image.open(path).size
    ar = iw / ih
    w, h = bw, bw / ar
    if h > bh:
        h, w = bh, bh * ar
    return w, h


