def set_ea(run, font_name):
    rPr = run._r.get_or_add_rPr()
    for tag in ("a:latin", "a:ea", "a:cs"):
        el = rPr.find(qn(tag))
        if el is None:
            el = rPr.makeelement(qn(tag), {})
            rPr.append(el)
        el.set("typeface", font_name)


def style_run(run, size, color, bold, font=CJK):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = font
    set_ea(run, font)


def set_bullet(p, char="·", marL=0.20, indent=-0.20):
    pPr = p._p.get_or_add_pPr()
    pPr.set("marL", str(int(marL * 914400)))
    pPr.set("indent", str(int(indent * 914400)))
    for t in ("a:buNone", "a:buChar", "a:buAutoNum"):
        e = pPr.find(qn(t))
        if e is not None:
            pPr.remove(e)
    bu = pPr.makeelement(qn("a:buChar"), {"char": char})
    buF = pPr.makeelement(qn("a:buFont"), {"typeface": "Arial"})
    pPr.append(buF)
    pPr.append(bu)
    return p


def no_bullet(p):
    pPr = p._p.get_or_add_pPr()
    for t in ("a:buChar", "a:buAutoNum"):
        e = pPr.find(qn(t))
        if e is not None:
            pPr.remove(e)
    pPr.append(pPr.makeelement(qn("a:buNone"), {}))
    return p


