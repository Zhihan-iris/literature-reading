# ---------------------------------------------------------------- spec helpers

def txt(x, y, w, h, runs, size=16, color=INK, bold=False, align="l",
        spacing=1.15, anchor="t"):
    """runs: str, or list of (text, bold, color, size) tuples."""
    return dict(kind="txt", x=x, y=y, w=w, h=h, runs=runs, size=size,
                color=color, bold=bold, align=align, spacing=spacing,
                anchor=anchor)


def bullets(x, y, w, h, items, size=16, color=INK, spacing=1.25, gap=8):
    return dict(kind="bul", x=x, y=y, w=w, h=h, items=items, size=size,
                color=color, spacing=spacing, gap=gap)


def eqb(x, y, w, h, lines, size=17, color=NAVY, align="c"):
    if isinstance(lines, str):
        lines = [lines]
    return dict(kind="eq", x=x, y=y, w=w, h=h, lines=lines, size=size,
                color=color, align=align)


def tbl(x, y, w, h, data, size=13, col_w=None, header=True, row_h=0.34,
        emphase=None):
    """emphase: dict {(r,c): True} cells rendered accent+bold."""
    return dict(kind="tbl", x=x, y=y, w=w, h=h, data=data, size=size,
                col_w=col_w, header=header, row_h=row_h, emphase=emphase or {})


def img(x, y, w, h, name, caption=None, cap_size=10.5, frame=True):
    return dict(kind="img", x=x, y=y, w=w, h=h, name=name, caption=caption,
                cap_size=cap_size, frame=frame)


def figurrow(x, y, w, h, items, gap=0.22, cap_size=10.5):
    """items: list of (asset_name, caption). Split w evenly."""
    return dict(kind="row", x=x, y=y, w=w, h=h, items=items, gap=gap,
                cap_size=cap_size)


def kpi(x, y, w, h, items, gap=0.20):
    """items: list of (number, label, highlight_bool)."""
    return dict(kind="kpi", x=x, y=y, w=w, h=h, items=items, gap=gap)


def callout(x, y, w, h, text, size=15, color=ACCENT, fill=RGBColor(0xFC, 0xF3, 0xF4)):
    return dict(kind="co", x=x, y=y, w=w, h=h, text=text, size=size,
                color=color, fill=fill)


def boxes(x, y, w, h, items, gap=0.24, size=15):
    """items: list of (heading, body). Rendered as bordered cards in a row."""
    return dict(kind="box", x=x, y=y, w=w, h=h, items=items, gap=gap, size=size)


def grid4(x, y, w, h, items, gap=0.24, size=15):
    """items: list of (heading, body) laid out 2x2."""
    return dict(kind="g4", x=x, y=y, w=w, h=h, items=items, gap=gap, size=size)


def kv(x, y, w, h, heading, items, size=12.5, gap=3, accent=ACCENT):
    """A heading plus label/value lines (label rendered bold).

    items: list of (label, value) tuples.
    """
    return dict(kind="kv", x=x, y=y, w=w, h=h, heading=heading, items=items,
                size=size, gap=gap, accent=accent)


